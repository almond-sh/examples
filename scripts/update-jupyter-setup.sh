#!/usr/bin/env bash
# Updates jupyter/ with the Jupyter setup of the dev.jupyter* Mill commands of almond
# (https://github.com/almond-sh/almond), from the examples/ directory of almond at a given git ref,
# so that the image the Dockerfile builds (and Binder) has the same JupyterLab, extensions and
# settings as these commands:
# - jupyter/requirements.txt: the Python packages of the main dependencies and of the "lab" and
#   "ai" dependency groups of examples/pyproject.toml, at the versions pinned in examples/uv.lock
#   (JupyterLab, the variable inspector, Jupyter AI, …)
# - jupyter/jupyterlab-overrides.json: the default JupyterLab settings
# - jupyter/acp-agents/: the ACP agents Jupyter AI uses for its Claude and Codex personas
# - jupyter/almond-commit: the almond commit these come from
#
# Usage: scripts/update-jupyter-setup.sh [almond git ref (branch, tag or commit), main by default]
# Requires curl and uv (https://docs.astral.sh/uv).
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

REF="${1:-main}"
COMMIT="$(curl -fsSL -H "Accept: application/vnd.github.sha" "https://api.github.com/repos/almond-sh/almond/commits/$REF")"
echo "Getting the Jupyter setup of almond $REF ($COMMIT)"

BASE="https://raw.githubusercontent.com/almond-sh/almond/$COMMIT/examples"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
for f in pyproject.toml uv.lock jupyterlab-overrides.json acp-agents/package.json acp-agents/package-lock.json; do
  mkdir -p "$TMP/$(dirname "$f")"
  curl -fsSL -o "$TMP/$f" "$BASE/$f"
done

mkdir -p jupyter/acp-agents
cp "$TMP/jupyterlab-overrides.json" jupyter/
cp "$TMP/acp-agents/package.json" "$TMP/acp-agents/package-lock.json" jupyter/acp-agents/
{
  echo "# Generated by scripts/update-jupyter-setup.sh, don't edit by hand: the main dependencies and the"
  echo "# \"lab\" and \"ai\" groups of the examples/pyproject.toml file of almond, at the versions of its"
  echo "# examples/uv.lock file, at almond commit $COMMIT"
  uv export --project "$TMP" --frozen --no-hashes --no-emit-project --no-header --group lab --group ai
} > jupyter/requirements.txt
echo "$COMMIT" > jupyter/almond-commit
